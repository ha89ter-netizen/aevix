import { test, expect } from "@playwright/test";
import { resolveNiche } from "../src/lib/niche";

/**
 * Коллизии распознавания ниши: слова, которые начинаются одинаково, а значат разное.
 *
 * `niche.spec.ts` проверяет, что нишу узнают ПРАВИЛЬНО. Здесь — обратное: что её не узнают ТАМ,
 * ГДЕ ЕЁ НЕТ. Это разные свойства, и второе ломается тише: маркетинговое агентство получает сайт
 * медицинской клиники, а поскольку резолвер один на анализ и на концепт, ошибка приходит
 * согласованной и оттого убедительной.
 *
 * Две разные причины, и лечатся они по-разному:
 *
 *   1. ПРЕФИКС ЛЕЗЕТ В ЧУЖОЕ СЛОВО. «розы» внутри «розыгрыша», «пион» внутри «пионерского»,
 *      «трен» внутри «тренингов». Совпадает начало, а корень другой. Это ровно тот класс, что
 *      уже ловили на коротких токенах («сто» в «ресторане», QA-1) — просто на другой длине.
 *
 *   2. СЛОВО ЧЕСТНО МНОГОЗНАЧНО. «анализ» бывает медицинский и рыночный, «курс» — учебный и
 *      валютный, «кухня» — ресторанная и мебельная. Тут префикс ни при чём: виновата
 *      неоднозначность самого слова, и решает её контекст рядом.
 *
 * Внизу — контрольные случаи. Они обязаны продолжать работать: правка, которая чинит коллизии,
 * ломая распознавание, хуже самой коллизии.
 */

test.describe("ниша: коллизии слов", () => {
  const NOT = [
    ["Маркетинговое агентство: анализ рынка, реклама и SMM", "medical"],
    ["Проводим бизнес-тренинги для отделов продаж", "fitness"],
    ["Изготавливаем кухни на заказ, мебель для дома", "restaurant"],
    ["Обмен валют, выгодный курс доллара", "education"],
    ["Розыгрыш призов для наших клиентов каждый месяц", "flowers"],
    ["Детский пионерский лагерь на лето", "flowers"],
  ] as const;

  for (const [input, wrong] of NOT) {
    test(`«${input.slice(0, 42)}…» — не ${wrong}`, () => {
      expect(resolveNiche(input).id, `распознано как ${wrong}, хотя речь о другом`).not.toBe(wrong);
    });
  }

  /**
   * Контроль. Ради починки коллизий нельзя разучиться узнавать то, ради чего сигналы и заведены:
   * падежи и производные слова обязаны совпадать по-прежнему.
   */
  const STILL = [
    ["Салон красоты и парикмахерская", "beauty"],
    ["Кабинет косметологии, косметолог принимает по записи", "beauty"],
    ["Автосервис: ремонт автомобилей и запчасти", "auto"],
    ["Ресторан на 80 мест, авторская кухня", "restaurant"],
    ["Цветочный магазин: розы, пионы и тюльпаны", "flowers"],
    ["Тренажёрный зал, тренировки с тренером", "fitness"],
    ["Медицинская клиника: анализы и диагностика", "medical"],
    ["Курсы английского языка для взрослых", "education"],
    ["Стоматология: лечение и имплантация зубов", "dental"],
  ] as const;

  for (const [input, expected] of STILL) {
    test(`«${input.slice(0, 42)}…» → ${expected}`, () => {
      expect(resolveNiche(input).id).toBe(expected);
    });
  }

  test("нераспознанное остаётся generic, а не приписывается ближайшей нише", () => {
    // Честный отказ лучше уверенной ошибки: generic показывает нейтральный профиль, а неверная
    // ниша — чужой контент под видом понятого бизнеса.
    for (const input of ["Считаем стоимость доставки", "Занимаемся всяким разным"]) {
      expect(resolveNiche(input).id, `«${input}»`).toBe("generic");
    }
  });
});
