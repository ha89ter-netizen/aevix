"use client";

import dynamic from "next/dynamic";

/**
 * Сцена грузится отдельно от экрана.
 *
 * Первый экран обязан появиться немедленно, а система — ожить следом: человек успевает прочесть
 * заголовок раньше, чем ему становится интересна графика. Сдвинуть при этом ничего не может —
 * место занято плоскостью с первого кадра, поэтому подгрузка происходит внутри уже готовой
 * композиции, а не вместо неё.
 */
const EcosystemGraph = dynamic(() => import("./ecosystem/EcosystemGraph"), { ssr: false });

/**
 * Плоскость, на которой живёт система.
 *
 * Это не заглушка и не место, оставленное «на потом». Это сцена: очерченное поле с собственными
 * границами и метками по углам, как окно на чертеже. Пустая сцена в театре выглядит законченной,
 * потому что у неё есть портал, — здесь работает ровно тот же закон. Раньше на этом месте была
 * неопределённость и подпись, извиняющаяся за отсутствие; законченная композиция не может
 * содержать записку о том, чего в ней нет.
 *
 * Всё, что здесь есть, останется после этапа 2. Экосистема встанет ВНУТРЬ плоскости и ничего не
 * заменит: рамка, метки и подпись сцены — постоянная архитектура, а не временная замена графике.
 *
 * Что плоскость гарантирует этапу 2:
 *
 * 1. **Устойчивая зона.** Размер задаётся соотношением сторон, а не содержимым, поэтому сцена
 *    появится внутри и не сдвинет ни заголовок, ни кнопки.
 * 2. **Независимый слой.** Свой контекст наложения; текст героя не знает геометрии будущих
 *    карточек, сцена не знает длины заголовка.
 * 3. **Границы.** `container-type: size` — сцена считает пропорции от плоскости, а не от окна:
 *    одна и та же сцена в широкой колонке и в узкой полосе без отдельных веток кода.
 * 4. **Запасной путь.** Устройства без WebGL и режим уменьшенной анимации получат внутри той же
 *    плоскости статический вариант — разметка для этого уже правильная.
 */
export function EcosystemSlot() {
  return (
    <div className="entry-ecosystem" role="img" aria-labelledby="entry-scene-name">
      <div className="entry-ecosystem-plane" data-ecosystem-stage>
        {/* Метки по углам — как приводочные кресты на чертеже: они сообщают, что поле измерено,
            а не просто оставлено пустым. Постоянная часть сцены. */}
        <span className="entry-plane-tick is-tl" aria-hidden="true" />
        <span className="entry-plane-tick is-tr" aria-hidden="true" />
        <span className="entry-plane-tick is-bl" aria-hidden="true" />
        <span className="entry-plane-tick is-br" aria-hidden="true" />
        <EcosystemGraph />
      </div>
    </div>
  );
}
