"use client";

import Link from "next/link";
import { LogIn } from "lucide-react";
import { useAuth } from "@/lib/auth-context";

/**
 * Вход в правом верхнем углу, рядом с основным целевым действием — виден из любой точки сайта,
 * включая лендинг, где боковой панели с аккаунтом нет.
 *
 * Тише консультации намеренно. У правой зоны шапки одно основное действие, и это по-прежнему
 * «Бесплатная консультация»: она приносит клиентов, а вход нужен уже пришедшим. Две одинаково
 * громкие кнопки рядом — ровно то, из-за чего прошлую шапку пришлось разбирать.
 *
 * Вошедшему не показывается ничего: регистрироваться ему незачем, а почта и выход есть в
 * боковой панели Workspace. Так в шапке не появляется третий элемент.
 *
 * Пока состояние входа неизвестно, места не занимает — иначе кнопка мигала бы у вошедшего при
 * каждой загрузке страницы.
 */
export function ShellHeaderAccount() {
  const { user, isLoaded, available } = useAuth();

  if (!isLoaded || user) return null;
  // Вход не настроен на сервере — вести к нему значит вести в тупик.
  if (!available) return null;

  return (
    // aria-label обязателен: на телефоне подпись прячется и остаётся один значок, у которого
    // иначе не было бы доступного имени вовсе.
    <Link href="/app/login" className="shell-header-login" aria-label="Войти в аккаунт">
      <LogIn className="h-4 w-4" />
      <span>Войти</span>
    </Link>
  );
}
