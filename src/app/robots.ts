import type { MetadataRoute } from "next";
import { absoluteUrl } from "@/lib/site";

/**
 * Что поисковику вообще имеет смысл читать.
 *
 * До этого прохода правило было одно — `allow: "/"` — и в индекс приглашались страница входа,
 * список проектов, настройки и API. Полезного там нет ни строки: содержание за аутентификацией,
 * а робот увидит пустую оболочку и отдаст её в выдачу вместо `/platform`.
 *
 * Это SEO-инструкция, а НЕ граница безопасности. Приватное закрыто владением и сессией в
 * маршрутах и репозитории; `Disallow` лишь просит вежливого робота не тратить обход. Робот
 * невежливый его проигнорирует — и упрётся в ту же проверку прав, что и любой чужой человек.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: "*",
      allow: "/",
      disallow: [
        // Весь Workspace двумя записями, а не одной. `"/app"` без слеша нельзя: правила
        // robots.txt — это префиксы, и такая строка закрыла бы заодно `/apple-icon.png`,
        // которым iOS рисует иконку сохранённой ссылки. Поэтому подпути закрывает `"/app/"`,
        // а сам список проектов — якорь конца адреса.
        "/app$",
        "/app/",
        "/api/",
      ],
    },
    sitemap: absoluteUrl("/sitemap.xml"),
    host: absoluteUrl("/").replace(/\/$/, ""),
  };
}
