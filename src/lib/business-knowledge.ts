/**
 * The knowledge layer behind every generated concept: instead of inventing a business niche
 * from scratch on each generation, the generator first loads this per-category knowledge —
 * page structure, the products-vs-services distinction, believable About content, FAQ, demo
 * reviews, demo contact data, image keywords and layout recommendations — and builds on top
 * of it. Every category reads differently on purpose: a coffee shop has a menu AND services
 * (delivery, catering), a barbershop has only services, a hotel sells rooms.
 *
 * All names, reviews, addresses and phone numbers here are DEMONSTRATION content. The UI is
 * required to mark them as demo wherever they render — this file deliberately contains no
 * real people or real businesses.
 */

export type KnowledgeOffer = { name: string; price: string };
export type KnowledgeReview = { name: string; when: string; text: string; stars: 4 | 5 };
export type KnowledgeFaqEntry = { q: string; a: string };
export type KnowledgeValue = { title: string; text: string };
export type KnowledgeTeamMember = { role: string; name: string };

export type BusinessKnowledge = {
  id: string;
  /**
   * Более тонкая identity внутри базы (этап 7, Wave 3), если резолвер её определил: у одной базы
   * `legal` подтипы law/accounting/consulting делят ОДИН профиль знаний, но различаются меткой и
   * словарём. Null, когда подтип не выделен. Downstream читает это поле, а НЕ распознаёт заново.
   */
  subtype?: string | null;
  /** Human label of the niche — used as the hero eyebrow when the wizard type is generic. */
  label: string;
  /** Substring keywords (lowercase, RU + EN) for matching free-text business types/names. */
  keywords: string[];
  /**
   * The products-vs-services distinction. `productsPageName` is the natural name of the
   * catalogue page for this niche («Меню», «Каталог», «Номера») or null when the niche sells
   * only services (a barbershop has no menu). `products` are the things sold; `services` are
   * what the business does for the customer — the two never render as the same list.
   */
  productsPageName: string | null;
  products: KnowledgeOffer[];
  services: KnowledgeOffer[];
  /** Natural title of the services block for this niche («Услуги», «Сервис для гостей»). */
  servicesTitle: string;
  ctas: { primary: string; secondary: string; final: string };
  about: {
    story: [string, string];
    mission: string;
    values: KnowledgeValue[];
    team: KnowledgeTeamMember[];
    whyUs: string[];
    /** One-line caption over the interior/process photo on the About page. */
    atmosphere: string;
  };
  faq: KnowledgeFaqEntry[];
  reviews: { rating: string; count: number; entries: KnowledgeReview[] };
  contact: {
    hours: Array<[string, string]>;
    address: string;
    phone: string;
    messenger: "WhatsApp" | "Telegram";
  };
  /** Search keywords describing what imagery suits this niche (documented intent for the
   * image layer — concept-images.ts holds the actually verified photo pools). */
  imageKeywords: string[];
  /** Layout recommendations in preference order — the generator picks from these. */
  layouts: ConceptLayoutId[];
  /** Visual styles that suit the niche, used when the user hasn't insisted on one. */
  styles: ConceptStyleId[];
  /**
   * Палитра по умолчанию для ниши — используется, когда человек не выбрал цвета сам.
   *
   * Раньше на этот случай стоял общий `["black", "gold"]`: салон красоты, стоматология и
   * автосервис получали одинаковый чёрно-золотой сайт. Стиль при этом уже подбирался по нише
   * (`styles` выше), а цвет — нет, и это была единственная часть облика, оставшаяся общей.
   *
   * Первый цвет задаёт светлую или тёмную основу сайта, поэтому порядок значим.
   */
  colors: ConceptColorId[];
};

