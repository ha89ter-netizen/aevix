/**
 * Канонический источник публичной identity AEVIX: origin, имя, описания, публичный контакт.
 *
 * До этого прохода боевой origin был написан четырьмя литералами `https://aevix.vercel.app` —
 * в `metadataBase`, в `robots.sitemap`, в `sitemap.ts` и в JSON-LD. Расходятся такие копии
 * молча: поисковик получает канонический адрес одного домена, карта сайта — другого, и понять
 * это можно только по индексу через неделю. Поэтому адрес здесь один.
 *
 * `aevix.org`, а не `aevix.vercel.app`: домен продукта — тот, что человек видит и пересылает,
 * а vercel-поддомен остаётся техническим адресом развёртывания. Canonical, указывающий на
 * поддомен хостинга, отдал бы поиску его вместо домена.
 */

/**
 * Боевой origin. Переопределяется `NEXT_PUBLIC_SITE_ORIGIN` — это нужно превью-развёртываниям и
 * возможному переезду домена, но значение по умолчанию боевое, а не localhost: страница,
 * собранная без переменной, обязана отдавать правильный canonical, а не тихо ссылаться на
 * машину сборщика.
 *
 * Хвостовой слеш срезается: `new URL("/platform", origin)` и шаблоны ниже дают его сами, и без
 * нормализации адрес превращался бы в `https://aevix.org//platform`.
 */
export const SITE_ORIGIN = (process.env.NEXT_PUBLIC_SITE_ORIGIN || "https://aevix.org").replace(/\/+$/, "");

/** Абсолютный URL публичного пути — для sitemap, JSON-LD и og:url. */
export const absoluteUrl = (path: string) => `${SITE_ORIGIN}${path.startsWith("/") ? path : `/${path}`}`;

export const SITE_NAME = "AEVIX";

/** Заголовок по умолчанию — он же заголовок входного экрана и подпись социальной карточки. */
export const SITE_TITLE = "AEVIX — операционная система для бизнеса";

/**
 * Описание по умолчанию. Обещает только то, что продукт делает: разбор, сайт, процессы, расчёт.
 * Ни сроков, ни процентов, ни числа клиентов — таких данных у нас нет, а в выдаче они выглядели
 * бы как подтверждённые.
 */
export const SITE_DESCRIPTION =
  "AEVIX собирает разбор, сайт, процессы и стоимость в одно рабочее пространство и держит их согласованными, пока бизнес растёт.";

/**
 * Публичный адрес AEVIX — тот, что показывается человеку и уходит в structured data.
 *
 * Он НЕ является получателем заявок: доставкой заведует серверная `LEADS_TO_EMAIL`, и совпадать
 * с этим адресом она не обязана. Смешать их — значит однажды напечатать внутренний почтовый
 * ящик на публичной странице.
 */
export const PUBLIC_CONTACT_EMAIL = "hello@aevix.org";

/**
 * Социальная карточка — один файл на весь сайт.
 *
 * Путь, размер и подпись объявлены здесь, а рисует картинку `app/opengraph-image.tsx`, который
 * читает ЭТИ значения. Направление важно: держать их в самом маршруте нельзя — он тянет за собой
 * `next/og`, и импорт из клиентского кода утащил бы рендерер картинок в браузерный бандл.
 *
 * Почему адрес указывается страницами явно, хотя файловая конвенция Next умеет подставлять его
 * сама: она привязывает картинку к СВОЕМУ сегменту. Корень её получал, а `/platform`, `/privacy`
 * и `/terms`, объявившие собственный `openGraph`, теряли — Next заменяет объект целиком, вместе
 * с подставленным `images`. Ссылка в Telegram приходила без картинки; поймано живой проверкой
 * разметки, из исходников это не видно.
 */
export const OG_IMAGE = {
  path: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: SITE_TITLE,
} as const;

/**
 * Метаданные публичной страницы: заголовок, описание, канонический адрес — и то же самое для
 * социальной карточки.
 *
 * Помощник, а не три строки в каждом `page.tsx`, из-за одного неочевидного правила Next:
 * `openGraph` НЕ достраивается из `title`/`description` страницы. Страница, объявившая только
 * их, наследует карточку родителя целиком — и `/platform`, `/privacy`, `/terms` уходили в
 * Telegram под одним и тем же заголовком корня, с `og:url`, указывающим на корень. Поймано
 * живой проверкой разметки, а не рассуждением.
 *
 * Картинка карточки — общая (`OG_IMAGE`), рисуется одним файлом; страницы лишь ссылаются на
 * неё, поэтому второго изображения в проекте не заводится.
 */
export function pageMetadata({
  title,
  description,
  path,
  titleIsWhole = false,
}: {
  title: string;
  description: string;
  path: string;
  /**
   * Заголовок уже содержит имя бренда и не должен проходить через шаблон `%s — AEVIX`.
   *
   * Нужно ровно одной странице — входному экрану, чей заголовок и есть `SITE_TITLE`. Без этого
   * вкладка называлась бы «AEVIX — операционная система для бизнеса — AEVIX».
   */
  titleIsWhole?: boolean;
}) {
  return {
    title: titleIsWhole ? { absolute: title } : title,
    description,
    alternates: { canonical: path },
    openGraph: {
      title,
      description,
      url: absoluteUrl(path),
      siteName: SITE_NAME,
      locale: "ru_RU",
      type: "website" as const,
      images: [
        {
          url: OG_IMAGE.path,
          width: OG_IMAGE.width,
          height: OG_IMAGE.height,
          alt: OG_IMAGE.alt,
        },
      ],
    },
    twitter: {
      card: "summary_large_image" as const,
      title,
      description,
      images: [OG_IMAGE.path],
    },
  };
}
