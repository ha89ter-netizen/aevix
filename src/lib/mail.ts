import { PUBLIC_CONTACT_EMAIL, SITE_NAME } from "@/lib/site";

/**
 * Отправитель писем AEVIX — один на все письма продукта.
 *
 * Литерал стоял в двух маршрутах сразу (`/api/lead` и `/api/auth/request`), и это не
 * стилистическая мелочь: письма начинают уходить с РАЗНЫХ адресов ровно тогда, когда кто-то
 * поправил один из двух. Адрес берётся из канонической identity (`lib/site`), поэтому второй
 * копии почтового адреса в проекте нет вовсе.
 *
 * По умолчанию — адрес на своём домене, а не sandbox `onboarding@resend.dev`, который стоял тут
 * раньше. Разница не косметическая: sandbox доставляет ТОЛЬКО на адрес владельца учётки Resend,
 * то есть форма выглядит рабочей, провайдер отвечает успехом, в логах всё зелено — а до человека
 * письмо не доходит. Домен в Resend настроен (DKIM `resend._domainkey`, SPF и MX на
 * `send.aevix.org`), и боевое значение стоит умолчанием по той же причине, что и боевой
 * `SITE_ORIGIN`: конфигурация, собранная без переменной, обязана быть верной, а не удобной для
 * разработки. Форк без этого домена задаёт `LEAD_EMAIL_FROM`.
 *
 * Имя переменной уже своего смысла: она задаёт отправителя и для кода входа тоже. Переименование
 * потребовало бы синхронной правки на Vercel, а рассинхрон здесь означает, что письма перестанут
 * уходить, — поэтому имя оставлено, а несоответствие описано.
 *
 * Читается на каждый вызов, а не один раз при импорте: так же, как `LEADS_TO_EMAIL` рядом, и по
 * той же причине — значение принадлежит развёртыванию, а не сборке.
 */
export function mailFrom(): string {
  return process.env.LEAD_EMAIL_FROM || `${SITE_NAME} <${PUBLIC_CONTACT_EMAIL}>`;
}
