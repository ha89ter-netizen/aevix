import type { ConceptStyleId } from "./website-concept";

/**
 * Композиционная система сгенерированных сайтов.
 *
 * Здесь лежит то, чего в продукте не было и из-за отсутствия чего разные стили выглядели
 * одинаково: связь стиля с ГЕОМЕТРИЕЙ, а не только с токенами.
 *
 * Разбор проблемы, ради которого этот файл и появился. Раньше `styleId` (13 штук) через
 * `generateVisualIdentity` управлял только `ConceptVisualTokens` — радиус, тень, трекинг, вес,
 * spacing. Всё декор. Композицию же задавала отдельная ось `layoutId` (3 варианта), и выбиралась
 * она НЕ стилем, а seed'ом от имени бизнеса. Значит выбор стиля не менял композицию вообще: два
 * стиля на одном бизнесе получали одну раскладку и отличались только цветом и радиусом. Критерий
 * «убери цвет и радиус — стили должны остаться различимы» проваливался by design.
 *
 * Лечение причины: стиль выбирает КОМПОЗИЦИОННОЕ СЕМЕЙСТВО. Семейство — это разная геометрия
 * (hero, ритм секций, подача услуг, работа с изображением), собранная из общих примитивов, а не
 * одна разметка с CSS-переключателями. Токены остаются вторым, независимым слоем поверх.
 *
 * Слои этапа 3, каждый со своей зоной ответственности:
 *   - семейство (здесь)         — геометрия: какой hero, какой ритм, как подаются услуги и фото;
 *   - токены (`styleDefinitions`) — характер: типографика, spacing, радиус, границы, плотность;
 *   - профиль бизнеса (`business-knowledge`) — что показывать и в каком приоритете;
 *   - контент (слой AI)         — конкретные тексты, услуги, цены, изображения.
 *
 * Style = семейство + токены. Поэтому четырнадцатый стиль — это новая КОМБИНАЦИЯ примитивов, а не
 * новая страница: он берёт существующее семейство (или новое, собранное из тех же примитивов) и
 * свой набор токенов.
 */

/**
 * Композиционные семейства. Их пять — намеренно немного: каждое должно быть узнаваемо отличным
 * даже на чёрно-белом каркасе, а не «ещё один оттенок сетки».
 */
export const COMPOSITION_FAMILIES = [
  "editorial",
  "gallery",
  "structured",
  "minimal",
  "technical",
  "organic",
] as const;

export type CompositionFamily = (typeof COMPOSITION_FAMILIES)[number];

/**
 * Как семейство строит первый экран. Это ГЕОМЕТРИЯ hero, а не его оформление, и именно она
 * лечит прежний баг: hero больше не зашит как «текст слева, фото справа» для всех тринадцати
 * стилей.
 *
 *  - `split`      — две колонки, текст и фото рядом; классика, но с безопасными границами;
 *  - `image-led`  — фото занимает большую часть экрана, текст лежит поверх снизу;
 *  - `statement`  — только типографика по центру, фото уходит отдельным блоком ниже;
 *  - `overlap`    — редакционный наезд: текст заходит на фото контролируемо и намеренно;
 *  - `canvas`     — асимметрия: текст в одном углу, фото смещено в противоположный.
 */
export type HeroKind = "split" | "image-led" | "statement" | "overlap" | "canvas";

/**
 * Как семейство подаёт услуги на главной. Полный каталог всегда живёт только на странице услуг —
 * здесь именно превью характера бизнеса.
 *
 *  - `cards`    — карточки с номерами, сдержанная сетка;
 *  - `list`     — типографический список, минимум рамок;
 *  - `columns`  — категории в колонках, для каталожных бизнесов;
 *  - `feature`  — одно-два направления крупно, остальное тихо.
 */
export type ServiceKind = "cards" | "list" | "columns" | "feature";

/** Как семейство обращается с изображениями — часть его характера, а не случайность. */
export type ImageTreatment = "framed" | "full-bleed" | "editorial-crop" | "accent" | "grid";

/** Ритм секций: плотный, обычный или просторный. Пауза — часть композиции. */
export type SectionRhythm = "tight" | "regular" | "airy";

export type FamilyComposition = {
  family: CompositionFamily;
  hero: HeroKind;
  services: ServiceKind;
  images: ImageTreatment;
  rhythm: SectionRhythm;
  /** Сколько направлений показывать на главной в превью услуг (полный список — на «Услугах»). */
  homeServiceCount: number;
};

/**
 * Определения семейств. Одно место, где геометрия каждого зафиксирована целиком, — отрисовка
 * читает отсюда и не принимает композиционных решений сама.
 */
export const FAMILY_COMPOSITION: Record<CompositionFamily, FamilyComposition> = {
  // Крупная типографика, асимметрия, фото как редакционное. Hero наезжает намеренно.
  editorial: { family: "editorial", hero: "overlap", services: "list", images: "editorial-crop", rhythm: "airy", homeServiceCount: 3 },
  // Изображение — главный материал. Hero почти целиком визуальный. Beauty, парфюм, рестораны.
  gallery: { family: "gallery", hero: "image-led", services: "feature", images: "full-bleed", rhythm: "regular", homeServiceCount: 3 },
  // Строгая сетка, сильная иерархия, минимум декора. Клиники, юристы, B2B.
  structured: { family: "structured", hero: "split", services: "columns", images: "framed", rhythm: "regular", homeServiceCount: 4 },
  // Предельно мало элементов, большие поля, одна крупная фотография. Ничего лишнего.
  minimal: { family: "minimal", hero: "statement", services: "cards", images: "accent", rhythm: "airy", homeServiceCount: 3 },
  // Жёсткая геометрия, контраст, необычная сетка. Выраженная типографика.
  technical: { family: "technical", hero: "canvas", services: "cards", images: "grid", rhythm: "tight", homeServiceCount: 4 },
  // Мягкая композиция, свободная сетка, крупные скругления. Без дешёвых blob'ов — характер
  // держат просторный split-hero и услуги колонками, а не декоративные пятна.
  organic: { family: "organic", hero: "split", services: "columns", images: "framed", rhythm: "airy", homeServiceCount: 3 },
};

/**
 * Тринадцать стилей → пять семейств. Это и есть «Style = семейство + токены»: у каждого стиля
 * своя геометрия, а не одна на всех.
 *
 * Маппинг выбран по характеру стиля, а не по алфавиту: editorial → редакционное семейство, glass
 * и luxury → визуальное (стеклу и роскоши идёт крупное фото), brutalist/tech/futuristic →
 * техническое (жёсткая геометрия), minimal/elegant/premium → минимальное (воздух), остальное
 * тяготеет к структурному. Токены при этом у каждого стиля СВОИ — семейство задаёт скелет, токены
 * одевают его по-разному, поэтому два стиля одного семейства всё равно различимы.
 */
export const STYLE_FAMILY: Record<ConceptStyleId, CompositionFamily> = {
  editorial: "editorial",
  bold: "editorial",
  glass: "gallery",
  luxury: "gallery",
  minimal: "minimal",
  elegant: "minimal",
  premium: "minimal",
  modern: "structured",
  soft: "organic",
  organic: "organic",
  brutalist: "technical",
  tech: "technical",
  futuristic: "technical",
};

export function familyForStyle(styleId: ConceptStyleId): CompositionFamily {
  return STYLE_FAMILY[styleId] ?? "structured";
}

export function compositionForStyle(styleId: ConceptStyleId): FamilyComposition {
  return FAMILY_COMPOSITION[familyForStyle(styleId)];
}

/**
 * Дескриптор композиции — для теста реального разнообразия.
 *
 * Тест сравнивает не пиксели, а эти строки: если два «разных» стиля дают одинаковый дескриптор,
 * они отличаются только токенами — ровно та болезнь, которую этап 3 лечит. Дескриптор нарочно НЕ
 * включает цвет и радиус: различие обязано держаться на геометрии.
 */
export function compositionDescriptor(styleId: ConceptStyleId): string {
  const c = compositionForStyle(styleId);
  return [c.family, c.hero, c.services, c.images, c.rhythm].join("/");
}

/* ==========================================================================
   АДАПТИВНАЯ ТИПОГРАФИКА (этап 3, дополнение)

   Copy и layout договариваются друг с другом. Нельзя сгенерировать произвольный текст, а потом
   впихивать его в готовый прямоугольник уменьшением шрифта до нечитаемости, обрезкой, многоточием
   или дефисом посреди слова — это дёшево выглядит. Поэтому у КАЖДОЙ роли текста есть бюджет:
   сколько слов, сколько строк, какой минимальный визуально приемлемый размер.

   Два независимых применения бюджета:
     1. Генерация (слой AI) получает бюджет ДО написания текста — модель пишет под композицию,
        а не наугад (см. describeCopyBudget → route.ts).
     2. Отрисовка (CSS) держит пол (`--concept-*-floor`) и потолок каждой роли и переносит
        строки как задумано — даже если текст всё-таки пришёл длиннее бюджета, он остаётся
        читаемым и не ломает композицию.

   Числа выведены из существующей шкалы (`concept-heading-scale`, размеры в globals.css), а не
   назначены магией: floor каждой роли — это её наименьший всё ещё сильный размер, ceiling — тот,
   что уже стоит в CSS. Роль не проваливается в body-текст только потому, что copy оказался
   длинным: если под floor текст не размещается красиво — менять надо copy или композицию, а не
   продолжать жать шрифт.
   ========================================================================== */

export type ConceptLang = "ru" | "en" | "kk";

/**
 * Бюджет заголовка hero — по ГЕОМЕТРИИ hero, потому что от неё зависит доступная ширина и
 * характер: statement стоит крупно по центру и хочет короткую законченную мысль; split несёт
 * заголовок в колонке и переживёт на слово-два длиннее.
 *
 *  - `words`  — желаемый диапазон слов (min…max);
 *  - `lines`  — целевое и максимальное число строк (намеренные 2 строки — это сильная
 *               композиция, а не проблема; проблема — случайный перенос);
 *  - `chars`  — примерный предел символов по языкам. Один предел на RU/EN/KZ нельзя: визуальная
 *               длина слов различается (кириллица и латиница близки, но KZ агглютинативен и слова
 *               длиннее — значит меньше слов на строку при той же ширине).
 */
export type HeroCopyBudget = {
  words: readonly [number, number];
  lines: readonly [number, number];
  chars: Readonly<Record<ConceptLang, number>>;
};

/**
 * Бюджеты заголовка по типу hero. Ширина колонки заголовка (см. `max-width` в globals.css, в ch)
 * — прямой источник: overlap/canvas режут заголовок в самой тесной мере (13–14ch), поэтому у них
 * бюджет строже; image-led и statement дают заголовку почти всю ширину.
 */
export const HERO_COPY_BUDGET: Record<HeroKind, HeroCopyBudget> = {
  // ~16ch колонка, крупный редакционный H1 — намеренно узкий и высокий столбец: 2–4 строки для
  // него норма (см. globals.css max-width overlap). Пользователь прямо разрешает Hero H1 в 2–4
  // строки в зависимости от семейства; редакционному подходит именно высокая стопка.
  overlap: { words: [3, 6], lines: [2, 4], chars: { ru: 40, en: 46, kk: 36 } },
  // ~15ch, самый тесный — техническая геометрия, заголовок-заявление, тоже высокий столбец.
  canvas: { words: [3, 6], lines: [2, 4], chars: { ru: 38, en: 44, kk: 34 } },
  // центр, ~18ch, крупнейший кегль — одна законченная мысль без подзаголовка внутри.
  statement: { words: [4, 7], lines: [2, 3], chars: { ru: 46, en: 54, kk: 42 } },
  // фото во весь экран, текст поверх, ~20ch — можно чуть длиннее, но всё ещё 2 строки.
  "image-led": { words: [4, 7], lines: [2, 3], chars: { ru: 48, en: 56, kk: 44 } },
  // две колонки, заголовок в своей — самый терпимый к длине.
  split: { words: [4, 8], lines: [2, 3], chars: { ru: 52, en: 60, kk: 48 } },
};

export function heroCopyBudget(styleId: ConceptStyleId): HeroCopyBudget {
  return HERO_COPY_BUDGET[compositionForStyle(styleId).hero];
}

/**
 * Человекочитаемый бюджет для промпта генерации. Не «напиши красивый заголовок», а design budget:
 * тип hero, диапазон слов, число строк, предел символов на текущем языке, характер. Конкретика
 * зависит от семейства и языка — ровно то, чего модели не хватало, чтобы попадать в композицию.
 */
export function describeCopyBudget(styleId: ConceptStyleId, lang: ConceptLang = "ru"): string {
  const comp = compositionForStyle(styleId);
  const b = HERO_COPY_BUDGET[comp.hero];
  return [
    `Композиция hero: ${comp.hero} (семейство ${comp.family}).`,
    `Заголовок H1: ${b.words[0]}–${b.words[1]} слов, до ${b.chars[lang]} символов, ${b.lines[0]}–${b.lines[1]} строки.`,
    `Одна законченная мысль. Без подзаголовка внутри H1, без двоеточий-перечислений, без искусственных дефисов и переносов.`,
    `Подзаголовок — отдельная короткая строка (1 предложение), не продолжение H1.`,
    `Названия услуг — короткие, до 3 слов: помещаются в карточку без обрезки.`,
    `Призывы (CTA) — 1–3 слова, целым словом.`,
  ].join(" ");
}
