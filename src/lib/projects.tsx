/**
 * The central object of the Workspace. A Project is one business worked on end-to-end: the AI
 * Consultant's analysis, the Design Studio's concept (which already carries its own selected
 * colors/style — see WebsiteConcept), and the Pricing calculator's form + result all live on the
 * SAME project instead of each tool inventing its own disconnected "saved item". There is no
 * separate `workflow` field: the workflow map is `analysis.flow`, already generated by the AI
 * Consultant — storing it twice would just be two copies that can drift apart.
 */
/** One exchange with the AI Designer: what was asked, what actually changed, and what it
 * suggested next. Stored so a later request can build on earlier decisions instead of treating
 * every edit as an isolated one-off. */
export type DesignerEntry = {
  id: string;
  at: number;
  request: string;
  /** Human-readable summary of the concrete changes applied. */
  changes: string[];
  /** Which part of the project the edit landed on, for the history list. */
  section: string;
  /** The follow-up the designer offered, if it had one worth making. */
  suggestion: string | null;
};

/**
 * One reversible step, stored as the FIELDS that changed rather than a full concept snapshot.
 * A designer edit touches a palette, a style, a layout, a page or one price — keeping only those
 * keeps the stack small enough to persist with the project instead of dying with the tab.
 */
export type ConceptDiff = Partial<Pick<WebsiteConcept, "colorIds" | "styleId" | "layoutId" | "offers" | "pages">>;

const DIFF_KEYS = ["colorIds", "styleId", "layoutId", "offers", "pages"] as const;

/** The fields of `from` that differ from `to` — i.e. what to write to get back to `from`. */
export function conceptDiff(from: WebsiteConcept | null, to: WebsiteConcept | null): ConceptDiff {
  if (!from) return {};
  const diff: ConceptDiff = {};
  for (const key of DIFF_KEYS) {
    if (!to || JSON.stringify(from[key]) !== JSON.stringify(to[key])) {
      Object.assign(diff, { [key]: from[key] });
    }
  }
  return diff;
}

export function applyConceptDiff(design: WebsiteConcept | null, diff: ConceptDiff): WebsiteConcept | null {
  if (!design) return design;
  return { ...design, ...diff };
}

