/**
 * Семантическая система иллюстраций «Процесса» (этап 4).
 *
 * Задача этапа 4 — превратить «Процесс» из схемы (иконка + подпись + линия ●─●─●) в визуальную
 * историю бизнеса: каждый шаг получает СВОЮ микро-сцену, которая ПОКАЗЫВАЕТ действие, а текст
 * лишь подтверждает. Иллюстрация объясняет — текст подтверждает.
 *
 * Данные процесса — это `analysis.flow`: 4–7 коротких строк-шагов, выведенных AI-анализом под
 * КОНКРЕТНЫЙ бизнес (салон, автосервис, ресторан, клиника, юрфирма, магазин). Строка не содержит
 * типа шага — тип определяется здесь, детерминированно, по корням слов. Один шаг → один
 * семантический тип → одна визуальная примитивная сцена. Поэтому один компонент рассказывает
 * РАЗНЫЕ процессы для разных ниш, а не подставляет существительные в одну историю.
 *
 * Слой намеренно чистый (без React): классификацию и вывод принципов можно проверить обычным
 * тестом, а не только скриншотом.
 */

/**
 * Семантические типы шага. Список закрыт намеренно: каждому типу соответствует одна узнаваемая
 * сцена из UI-примитивов (см. ProcessIllustration). Порядок — от начала пути клиента к результату,
 * но реальную последовательность задаёт сам процесс.
 */
export const PROCESS_STAGE_TYPES = [
  "message", // входящее сообщение/обращение
  "capture", // разбор обращения на параметры
  "analysis", // осмысление запроса
  "scheduling", // подбор времени/слота
  "payment", // оплата/счёт
  "crm", // запись в систему/базу
  "notification", // подтверждение/уведомление клиенту
  "review", // отзыв/оценка
  "document", // документ/договор
  "delivery", // выдача/доставка результата
  "inventory", // склад/остатки
  "handoff", // передача человеку/специалисту
  "completion", // завершение/результат
] as const;

export type ProcessStageType = (typeof PROCESS_STAGE_TYPES)[number];

/**
 * Правила классификации: корни слов → тип. Порядок важен — более специфичные типы идут раньше
 * общих, чтобы «клиент оплачивает» ушёл в payment, а не в message по слову «клиент». Ключи — по
 * корням, чтобы ловить падежи и формы («запись», «записи», «записать»).
 */
const CLASSIFY_RULES: Array<{ type: ProcessStageType; roots: string[] }> = [
  { type: "payment", roots: ["оплат", "плат", "счёт", "счет", "предоплат", "деньг", "касс", "чек"] },
  { type: "review", roots: ["отзыв", "оцен", "рейтинг", "обратн"] },
  { type: "document", roots: ["договор", "документ", "акт", "справк", "накладн", "смет", "наряд", "оформля", "оформлен"] },
  { type: "scheduling", roots: ["расписан", "календар", "слот", "врем", "дата", "брон", "свободн", "приём", "визит"] },
  { type: "delivery", roots: ["доставк", "выда", "отгруз", "вруч", "готов заказ", "получа заказ", "передан клиент"] },
  { type: "inventory", roots: ["склад", "остат", "налич", "инвентар", "товар на"] },
  { type: "notification", roots: ["подтвержд", "уведом", "напомин", "оповещ", "статус", "отправ ответ"] },
  // handoff и crm стоят ДО общих слов: «мастер видит запись» — это передача человеку, а не
  // расписание; «фиксируется/сохраняется» — это запись в систему, а не входящее.
  { type: "handoff", roots: ["команд", "менеджер", "мастер", "сотрудник", "специалист", "врач", "передаётся", "передаетс", "передан мастер"] },
  { type: "crm", roots: ["crm", "систем", "база", "карточк", "учёт", "учет", "фиксир", "сохран", "создаётся запис", "создает запис", "запись создан", "заказ-наряд"] },
  { type: "analysis", roots: ["анализ", "понима", "понят", "распозна", "определ", "разбир", "разобран", "классифи", "выявля"] },
  // capture — приём входящего: «оставляет заявку», «принимается запрос». Стоит перед message,
  // чтобы действие клиента-заявителя читалось как приём, а не просто «сообщение».
  { type: "capture", roots: ["оставля", "принима", "собира", "заполня", "заявк", "запрос", "обращ форм", "парам"] },
  { type: "message", roots: ["клиент", "гость", "пишет", "обращ", "звон", "сообщ", "whatsapp", "telegram", "чат", "отвеча", "бот", "делает заказ"] },
  { type: "completion", roots: ["заверш", "результат", "выполн", "итог", "закрыт", "готово"] },
];

/** Тип шага по его тексту. Ничего не совпало — «completion» как нейтральный «результат шага». */
export function classifyStage(step: string): ProcessStageType {
  const text = step.toLowerCase();
  for (const rule of CLASSIFY_RULES) {
    if (rule.roots.some((root) => text.includes(root))) return rule.type;
  }
  return "completion";
}

/**
 * Короткая подпись-подтверждение по типу. Она НЕ пересказывает иллюстрацию (та показывает
 * действие) и не повторяет заголовок — называет СОСТОЯНИЕ после шага, в 2–3 слова. «Текст
 * подтверждает».
 */
const TYPE_CAPTION: Record<ProcessStageType, string> = {
  message: "входящее принято",
  capture: "разобрано на детали",
  analysis: "запрос понят",
  scheduling: "время найдено",
  payment: "оплата учтена",
  crm: "сохранено в системе",
  notification: "клиент уведомлён",
  review: "отзыв собран",
  document: "документ готов",
  delivery: "передано клиенту",
  inventory: "остатки обновлены",
  handoff: "передано специалисту",
  completion: "этап завершён",
};

export function captionFor(type: ProcessStageType): string {
  return TYPE_CAPTION[type];
}

export type ProcessStage = {
  index: number;
  /** Нормализованный короткий заголовок (из flow). */
  title: string;
  type: ProcessStageType;
  /** Подпись-подтверждение состояния. */
  caption: string;
};

/**
 * Нормализация заголовка шага под типографику (этап 3 концептуально): убираем лишние пробелы и
 * завершающую пунктуацию, схлопываем двойные пробелы. НЕ обрезаем значимый текст многоточием —
 * если строка длинная, её переносит вёрстка между словами; короткость обеспечивается ещё на
 * генерации (см. подсказку flow в business-analysis).
 */
export function normalizeStageTitle(step: string): string {
  return step.trim().replace(/\s+/g, " ").replace(/[.;:]+$/, "");
}

/** Разбор всего процесса: каждый шаг → {заголовок, тип, подпись}. Детерминированно. */
export function describeProcess(steps: string[]): ProcessStage[] {
  return steps.map((step, index) => {
    const type = classifyStage(step);
    return { index, title: normalizeStageTitle(step), type, caption: TYPE_CAPTION[type] };
  });
}

export type ProcessPrinciple = { key: string; text: string };

/**
 * Принципы «Почему именно так» ВЫВОДЯТСЯ из состава процесса, а не одинаковы для всех: набор
 * присутствующих типов решает, какие системные эффекты назвать. Салон с записью и клиника с
 * документами получат разные принципы. Возвращает 2–3 в порядке приоритета.
 *
 * Блок завершает историю системным эффектом и НЕ повторяет карточки: карточка — про шаг,
 * иллюстрация — про действие, здесь — про эффект на бизнес в целом.
 */
const PRINCIPLE_RULES: Array<{ key: string; types: ProcessStageType[]; text: string }> = [
  { key: "faster", types: ["message", "notification"], text: "Клиент получает ответ быстрее — без ожидания у телефона." },
  { key: "nolost", types: ["capture", "crm", "document"], text: "Информация не теряется между каналами: всё в одном месте." },
  { key: "lessmanual", types: ["scheduling", "handoff", "completion", "delivery"], text: "Меньше ручных действий на каждом шаге." },
  { key: "structured", types: ["analysis", "capture"], text: "Каждое обращение разбирается по сути, а не теряется в переписке." },
  { key: "money", types: ["payment"], text: "Оплата под контролем на каждом шаге." },
  { key: "feedback", types: ["review"], text: "Обратная связь собирается сама и работает на репутацию." },
  { key: "stock", types: ["inventory"], text: "Остатки и наличие всегда актуальны." },
];

export function processPrinciples(steps: string[], limit = 3): ProcessPrinciple[] {
  const present = new Set(steps.map(classifyStage));
  const picked: ProcessPrinciple[] = [];
  for (const rule of PRINCIPLE_RULES) {
    if (rule.types.some((t) => present.has(t))) picked.push({ key: rule.key, text: rule.text });
    if (picked.length >= limit) break;
  }
  // Гарантируем минимум два принципа: если процесс совсем короткий, добираем общими, но всё ещё
  // истинными для любого автоматизированного процесса.
  if (picked.length < 2) {
    for (const fallback of PRINCIPLE_RULES) {
      if (!picked.some((p) => p.key === fallback.key)) picked.push({ key: fallback.key, text: fallback.text });
      if (picked.length >= 2) break;
    }
  }
  return picked;
}

/**
 * Раскладка «без сироты» для любого числа шагов. Первая карточка — ведущая (во всю ширину, вход в
 * историю). Остальные идут парами; если их нечётное число, последняя тоже раскрывается во всю
 * ширину — закрывает историю и не висит сиротой слева. Возвращает для каждого индекса, широкая ли
 * карточка. 3/4/5/6/7/10 шагов выглядят намеренно, а не как остаток деления.
 */
export function stageWidths(count: number): boolean[] {
  if (count <= 0) return [];
  if (count === 1) return [true];
  const widths = new Array(count).fill(false);
  widths[0] = true; // ведущая
  const restCount = count - 1;
  if (restCount % 2 === 1) widths[count - 1] = true; // нечётный остаток — закрывающая во всю ширину
  return widths;
}
