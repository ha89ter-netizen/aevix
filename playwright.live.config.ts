import { defineConfig } from "@playwright/test";

const PORT = 3000;
const BASE_URL = `http://localhost:${PORT}`;

try {
  process.loadEnvFile(".env.local");
} catch {
  // Файла нет — набор пропустит себя сам.
}

/**
 * Отдельный набор против НАСТОЯЩЕГО OpenAI. Запуск: `pnpm test:live`.
 *
 * Живёт отдельным конфигом и отдельной папкой намеренно. Основной набор (`pnpm test`) мокает
 * OpenAI и обязан оставаться быстрым и не зависеть от чужого сервиса; этот — наоборот, только
 * ради того, чтобы убедиться, что живой путь ещё жив. Смешивать их значит потерять оба
 * свойства сразу.
 *
 * Стоит денег: каждый прогон делает несколько настоящих запросов к модели. Гонять по поводу —
 * после правок в маршрутах, при смене модели или параметров запроса, — а не в каждом цикле.
 *
 * Браузер не нужен: это проверка контракта HTTP-маршрутов, и она делается через `request`.
 */
export default defineConfig({
  testDir: "./tests-live",
  fullyParallel: false,
  // Один воркер и один проект: у маршрутов стоит ограничение в 5 запросов в минуту на клиента,
  // и параллельный прогон упёрся бы в него, а не в предмет проверки.
  workers: 1,
  // Маршруты дают модели до 22 секунд, плюс сеть и холодная компиляция маршрута.
  timeout: 90_000,
  // Одна попытка повтора: чужой сервис имеет право икнуть. Настоящая поломка провалится дважды
  // и останется красной, а разовая сетевая осечка будет помечена как flaky, а не свалит прогон.
  retries: 1,
  reporter: [["list"]],
  use: { baseURL: BASE_URL },
  webServer: {
    command: "pnpm dev",
    url: BASE_URL,
    reuseExistingServer: true,
    timeout: 120_000,
  },
});
